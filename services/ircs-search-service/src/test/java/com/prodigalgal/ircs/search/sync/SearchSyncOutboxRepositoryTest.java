package com.prodigalgal.ircs.search.sync;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Timestamp;
import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

class SearchSyncOutboxRepositoryTest {

    private EmbeddedDatabase database;

    @AfterEach
    void shutdownDatabase() {
        if (database != null) {
            database.shutdown();
        }
    }

    @Test
    void claimsDueTasksAndMarksFailuresWithBackoffAndDeadLetter() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(database());
        createTable(jdbcTemplate);
        UUID id = UUID.randomUUID();
        insertTask(jdbcTemplate, id, "RAW_VIDEO", "INDEX", "PENDING", 0, Instant.now().minusSeconds(5));
        insertTask(jdbcTemplate, id, "RAW_VIDEO", "DELETE", "PENDING", 4, Instant.now().minusSeconds(5));
        SearchSyncOutboxRepository repository = new SearchSyncOutboxRepository(
                jdbcTemplate,
                new NamedParameterJdbcTemplate(jdbcTemplate));

        List<SearchSyncTaskRecord> claimed = repository.claimDue(10, "worker-1", Duration.ofSeconds(60));

        assertThat(claimed).hasSize(2);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM search_sync_tasks WHERE status = 'PROCESSING'",
                Integer.class)).isEqualTo(2);

        repository.markFailed(claimed, 5, Duration.ofSeconds(300), new RuntimeException("rabbit down"));

        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM search_sync_tasks WHERE status = 'PENDING'",
                Integer.class)).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM search_sync_tasks WHERE status = 'DEAD_LETTER'",
                Integer.class)).isEqualTo(1);
    }

    @Test
    void restoresExpiredProcessingLeases() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(database());
        createTable(jdbcTemplate);
        insertTask(jdbcTemplate, UUID.randomUUID(), "RAW_VIDEO", "INDEX", "PROCESSING", 1, Instant.now().minusSeconds(5));
        jdbcTemplate.update("""
                UPDATE search_sync_tasks
                   SET locked_by = 'worker-1',
                       locked_until = ?
                """, Timestamp.from(Instant.now().minusSeconds(30)));
        SearchSyncOutboxRepository repository = new SearchSyncOutboxRepository(
                jdbcTemplate,
                new NamedParameterJdbcTemplate(jdbcTemplate));

        int restored = repository.restoreExpiredProcessingLeases();

        assertThat(restored).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT status FROM search_sync_tasks",
                String.class)).isEqualTo("PENDING");
    }

    private EmbeddedDatabase database() {
        database = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        return database;
    }

    private void createTable(JdbcTemplate jdbcTemplate) {
        jdbcTemplate.execute("""
                CREATE TABLE search_sync_tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entity_type VARCHAR(50) NOT NULL,
                    entity_id UUID NOT NULL,
                    operation VARCHAR(20) NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    retry_count INT DEFAULT 0,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NOT NULL,
                    next_retry_at TIMESTAMP NOT NULL,
                    source_service VARCHAR(128),
                    correlation_id VARCHAR(128),
                    locked_by VARCHAR(128),
                    locked_until TIMESTAMP,
                    last_attempt_at TIMESTAMP,
                    last_error VARCHAR(2000)
                )
                """);
    }

    private void insertTask(
            JdbcTemplate jdbcTemplate,
            UUID id,
            String entityType,
            String operation,
            String status,
            int retryCount,
            Instant nextRetryAt) {
        Instant now = Instant.now();
        jdbcTemplate.update("""
                INSERT INTO search_sync_tasks
                    (entity_type, entity_id, operation, status, retry_count,
                     created_at, updated_at, next_retry_at, source_service, correlation_id)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                entityType,
                id,
                operation,
                status,
                retryCount,
                Timestamp.from(now),
                Timestamp.from(now),
                Timestamp.from(nextRetryAt),
                "test",
                id.toString());
    }
}

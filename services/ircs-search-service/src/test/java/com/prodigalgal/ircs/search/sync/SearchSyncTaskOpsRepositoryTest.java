package com.prodigalgal.ircs.search.sync;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Timestamp;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

class SearchSyncTaskOpsRepositoryTest {

    private EmbeddedDatabase database;

    @AfterEach
    void shutdownDatabase() {
        if (database != null) {
            database.shutdown();
        }
    }

    @Test
    void aggregatesSearchSyncTaskStats() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(database());
        jdbcTemplate.execute("""
                CREATE TABLE search_sync_tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entity_type VARCHAR(50) NOT NULL,
                    operation VARCHAR(20) NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    retry_count INT DEFAULT 0,
                    created_at TIMESTAMP NOT NULL,
                    next_retry_at TIMESTAMP NOT NULL
                )
                """);
        Instant now = Instant.now().truncatedTo(ChronoUnit.MILLIS);
        insertTask(jdbcTemplate, "RAW_VIDEO", "INDEX", "PENDING", 2,
                now.minusSeconds(120), now.minusSeconds(10));
        insertTask(jdbcTemplate, "UNIFIED_VIDEO", "INDEX", "PENDING", 0,
                now.minusSeconds(60), now.plusSeconds(3600));
        insertTask(jdbcTemplate, "UNIFIED_VIDEO", "DELETE", "COMPLETED", 1,
                now.minusSeconds(30), now.minusSeconds(20));
        insertTask(jdbcTemplate, "RAW_VIDEO", "INDEX", "FAILED", 5,
                now.minusSeconds(15), now.minusSeconds(5));

        SearchSyncTaskStatsResponse stats = new SearchSyncTaskOpsRepository(jdbcTemplate).stats();

        assertThat(stats.available()).isTrue();
        assertThat(stats.unavailableReason()).isNull();
        assertThat(stats.total()).isEqualTo(4);
        assertThat(stats.pending()).isEqualTo(2);
        assertThat(stats.completed()).isEqualTo(1);
        assertThat(stats.failed()).isEqualTo(1);
        assertThat(stats.duePending()).isEqualTo(1);
        assertThat(stats.rawVideo()).isEqualTo(2);
        assertThat(stats.unifiedVideo()).isEqualTo(2);
        assertThat(stats.indexOperations()).isEqualTo(3);
        assertThat(stats.deleteOperations()).isEqualTo(1);
        assertThat(stats.maxRetryCount()).isEqualTo(5);
        assertThat(stats.oldestPendingAt()).isEqualTo(now.minusSeconds(120));
        assertThat(stats.nextDueAt()).isEqualTo(now.minusSeconds(10));
    }

    @Test
    void returnsUnavailableWhenOutboxTableIsMissing() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(database());

        SearchSyncTaskStatsResponse stats = new SearchSyncTaskOpsRepository(jdbcTemplate).stats();

        assertThat(stats.available()).isFalse();
        assertThat(stats.unavailableReason()).isEqualTo("search_sync_tasks_unavailable");
        assertThat(stats.total()).isZero();
    }

    private EmbeddedDatabase database() {
        database = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        return database;
    }

    private void insertTask(
            JdbcTemplate jdbcTemplate,
            String entityType,
            String operation,
            String status,
            int retryCount,
            Instant createdAt,
            Instant nextRetryAt) {
        jdbcTemplate.update("""
                INSERT INTO search_sync_tasks
                    (entity_type, operation, status, retry_count, created_at, next_retry_at)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                entityType,
                operation,
                status,
                retryCount,
                Timestamp.from(createdAt),
                Timestamp.from(nextRetryAt));
    }
}

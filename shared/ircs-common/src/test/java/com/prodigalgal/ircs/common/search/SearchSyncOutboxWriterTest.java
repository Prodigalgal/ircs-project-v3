package com.prodigalgal.ircs.common.search;

import static org.assertj.core.api.Assertions.assertThat;

import com.prodigalgal.ircs.contracts.search.SearchEntityType;
import com.prodigalgal.ircs.contracts.search.SyncOperation;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

class SearchSyncOutboxWriterTest {

    private EmbeddedDatabase database;

    @AfterEach
    void shutdownDatabase() {
        if (database != null) {
            database.shutdown();
        }
    }

    @Test
    void enqueuesDistinctTasksIntoPersistentOutbox() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(database());
        createTable(jdbcTemplate);
        UUID id = UUID.randomUUID();
        SearchSyncOutboxWriter writer = new SearchSyncOutboxWriter(
                jdbcTemplate,
                "content-service");

        int accepted = writer.enqueueBatch(
                List.of(id, id, UUID.randomUUID()),
                SearchEntityType.RAW_VIDEO,
                SyncOperation.INDEX,
                "content-service",
                "trace-1");

        assertThat(accepted).isEqualTo(2);
        List<String> rows = jdbcTemplate.query("""
                SELECT entity_type || ':' || operation || ':' || status || ':' || source_service || ':' || correlation_id
                  FROM search_sync_tasks
                 ORDER BY id
                """, (rs, rowNum) -> rs.getString(1));
        assertThat(rows).containsExactly(
                "RAW_VIDEO:INDEX:PENDING:content-service:trace-1",
                "RAW_VIDEO:INDEX:PENDING:content-service:trace-1");
    }

    private EmbeddedDatabase database() {
        database = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        return database;
    }

    private void createTable(JdbcTemplate jdbcTemplate) {
        jdbcTemplate.execute("""
                CREATE TABLE search_sync_tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entity_type VARCHAR(50) NOT NULL,
                    entity_id UUID NOT NULL,
                    operation VARCHAR(20) NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    retry_count INT DEFAULT 0,
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NOT NULL,
                    next_retry_at TIMESTAMP NOT NULL,
                    source_service VARCHAR(128),
                    correlation_id VARCHAR(128)
                )
                """);
    }
}
